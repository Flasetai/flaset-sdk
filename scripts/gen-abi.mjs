// Generates src/deals/abi.ts and src/deals/addresses.ts from deployments/*.json.
// Fails if the ABIs differ between chains (all chains run the same build).
// Usage: node scripts/gen-abi.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';

const CHAINS = [4663, 8453, 56, 1];
const root = new URL('../', import.meta.url);
const read = (id) => JSON.parse(readFileSync(new URL(`deployments/${id}.json`, root), 'utf8'));

const first = read(CHAINS[0]).contracts;
for (const id of CHAINS.slice(1)) {
  const c = read(id).contracts;
  for (const name of ['FlasetDeals', 'FlasetRegistry']) {
    if (JSON.stringify(c[name].abi) !== JSON.stringify(first[name].abi)) throw new Error(`${name} ABI on chain ${id} differs from chain ${CHAINS[0]}`);
  }
}
const lockup = JSON.parse(readFileSync(new URL('scripts/sablier-lockup-abi.json', root), 'utf8'));

const out = `// Generated by scripts/gen-abi.mjs from deployments/*.json. Do not edit by hand.

/** FlasetDeals, as verified on Sourcify on every chain */
export const flasetDealsAbi = ${JSON.stringify(first.FlasetDeals.abi, null, 2)} as const;

/** FlasetRegistry, as verified on Sourcify on every chain */
export const flasetRegistryAbi = ${JSON.stringify(first.FlasetRegistry.abi, null, 2)} as const;

/** The reads this SDK makes on Sablier's Lockup, where FlasetDeals puts the vested share */
export const sablierLockupAbi = ${JSON.stringify(lockup, null, 2)} as const;
`;

const addresses = Object.fromEntries(
  CHAINS.map((id) => {
    const d = read(id);
    const c = d.contracts;
    const lean = (x) => ({ address: x.address, deployBlock: x.deployBlock, deployTx: x.deployTx });
    return [id, { chainId: d.chainId, name: d.name, FlasetDeals: lean(c.FlasetDeals), FlasetRegistry: lean(c.FlasetRegistry), SablierLockup: { address: c.SablierLockup.address } }];
  }),
);
const addressesOut = `// Generated by scripts/gen-abi.mjs from deployments/*.json. Do not edit by hand.

export const ADDRESSES = ${JSON.stringify(addresses, null, 2)} as const;
`;

for (const [file, text] of [['src/deals/abi.ts', out], ['src/deals/addresses.ts', addressesOut]]) {
  const target = new URL(file, root);
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== text) throw new Error(`${file} is out of date: run node scripts/gen-abi.mjs`);
    console.log(`${file} is up to date`);
  } else {
    writeFileSync(target, text);
    console.log(`wrote ${file}`);
  }
}
